# ======================================================
# ① 실습에 필요한 라이브러리 준비
# ======================================================
# argparse는 터미널 옵션을 받습니다. Path는 폴더와 파일 경로를 관리합니다.
# pandas는 여러 Scenario의 CSV를 읽고 하나의 비교표로 합칩니다.
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd


# ======================================================
# ② 프로젝트 ROOT 폴더 찾기
# ======================================================
# 이 파일을 scripts 폴더에 저장한다고 가정합니다.
# parents[1]은 scripts의 상위인 프로젝트 ROOT를 가리킵니다.
ROOT = Path(__file__).resolve().parents[1]

# ======================================================
# ③ 48번 Tracking 요약 CSV 입력 폴더 지정
# ======================================================
# 48번에서 생성한 *_tracking_summary.csv 파일들이 모인
# reports/day08/logs 폴더를 기본 입력 위치로 정합니다.
DEFAULT_LOG_DIR = (
    ROOT / "reports" / "day08" / "logs"
)

# ======================================================
# ④ Scenario 비교 결과 CSV 경로 지정
# ======================================================
# 세 Scenario의 결과를 하나로 합친 CSV를
# reports/day08/experiments/tracking_scenario_summary.csv에 저장합니다.
DEFAULT_OUTPUT_PATH = (
    ROOT
    / "reports"
    / "day08"
    / "experiments"
    / "tracking_scenario_summary.csv"
)

# ======================================================
# ⑤ 비교할 기본 SBU Scenario 세 개 정의
# ======================================================
# 8일차에서 사용하는 세 영상의 파일명 stem(확장자 제외)을 지정합니다.
# 이름 뒤에 _tracking_summary.csv를 붙여 입력 파일을 찾습니다.
DEFAULT_SCENARIOS = [
    "01_sbu_shaking_hands",
    "02_sbu_hugging",
    "03_sbu_kicking_challenge",
]


# ======================================================
# ⑥ 터미널 실행 옵션 처리 함수 정의
# ======================================================
# ArgumentParser를 만들고, 로그 폴더·출력 파일·Scenario 목록을
# 실행할 때 변경할 수 있도록 옵션을 등록합니다.
def parse_args():
    parser = argparse.ArgumentParser()

    # ======================================================
    # ⑦ 입력 로그 폴더 --log-dir 옵션 추가
    # ======================================================
    # 비교 대상 CSV가 다른 폴더에 있다면 --log-dir로 지정합니다.
    # 생략하면 DEFAULT_LOG_DIR을 사용합니다.
    parser.add_argument(
        "--log-dir",
        default=str(
            DEFAULT_LOG_DIR
        ),
    )

    # ======================================================
    # ⑧ 결과 저장 경로 --output 옵션 추가
    # ======================================================
    # 비교표 CSV 저장 파일 경로를 직접 지정할 수 있습니다.
    # 옵션을 생략하면 기본 experiments 폴더에 저장합니다.
    parser.add_argument(
        "--output",
        default=str(
            DEFAULT_OUTPUT_PATH
        ),
    )

    # ======================================================
    # ⑨ 비교할 Scenario를 여러 개 받는 옵션
    # ======================================================
    # nargs="+"는 Scenario 이름을 한 개 이상 연속해서 받을 수 있다는 뜻입니다.
    # 예: --scenarios challenge_crossing challenge_exit_reentry
    # 옵션이 없으면 기본 세 Scenario를 분석합니다.
    parser.add_argument(
        "--scenarios",
        nargs="+",
        default=DEFAULT_SCENARIOS,
        help=(
            "비교할 Scenario stem. "
            "예: challenge_crossing "
            "challenge_exit_reentry"
        ),
    )

    # ======================================================
    # ⑩ 명령행 옵션을 분석하고 반환
    # ======================================================
    # 터미널에서 입력된 값들을 읽어 args 객체로 반환합니다.
    # main 함수에서 args.log_dir, args.output, args.scenarios로 사용합니다.
    return parser.parse_args()


# ======================================================
# ⑪ main 함수 시작 및 실행 옵션 읽기
# ======================================================
# 프로그램의 실제 비교 작업이 시작되는 부분입니다.
# parse_args()를 호출해 사용자가 선택한 조건을 가져옵니다.
def main() -> None:
    args = parse_args()

    # ======================================================
    # ⑫ 입력 로그 폴더를 Path 객체로 변환
    # ======================================================
    # 문자열로 전달된 로그 폴더 경로를 Path로 바꿉니다.
    # 이후 파일 경로 연결과 절대경로 검사에 사용합니다.
    log_dir = Path(
        args.log_dir
    )

    # ======================================================
    # ⑬ 출력 파일 경로를 Path 객체로 변환
    # ======================================================
    # 결과 CSV의 저장 경로 역시 Path로 변환합니다.
    output_path = Path(
        args.output
    )

    # ======================================================
    # ⑭ 입력 폴더의 상대경로를 ROOT 기준으로 처리
    # ======================================================
    # 입력 로그 폴더가 상대경로이면 프로젝트 ROOT를 앞에 붙입니다.
    # 절대경로는 변경하지 않습니다.
    if not log_dir.is_absolute():
        log_dir = ROOT / log_dir

    # ======================================================
    # ⑮ 출력 경로의 상대경로를 ROOT 기준으로 처리
    # ======================================================
    # 출력 CSV 경로도 같은 방식으로 통일합니다.
    # 프로젝트 어느 위치에서 실행하더라도 기준 경로를 유지합니다.
    if not output_path.is_absolute():
        output_path = (
            ROOT / output_path
        )

    # ======================================================
    # ⑯ Scenario별 비교 행을 모을 빈 목록 준비
    # ======================================================
    # 각 Scenario 요약 CSV에서 읽은 한 행을 rows에 모읍니다.
    # 반복문이 끝나면 rows를 하나의 DataFrame으로 변환합니다.
    rows = []

    # ======================================================
    # ⑰ 선택한 Scenario를 하나씩 반복 처리
    # ======================================================
    # 기본 설정이라면 SBU 영상 세 개의 결과를 차례대로 읽습니다.
    # --scenarios를 지정했다면 입력한 목록을 순서대로 처리합니다.
    for scenario in args.scenarios:
        # ======================================================
        # ⑱ Scenario 이름으로 요약 CSV 파일 경로 만들기
        # ======================================================
        # Scenario stem 뒤에 _tracking_summary.csv를 붙입니다.
        # 예: 01_sbu_shaking_hands_tracking_summary.csv
        # 이 파일은 48번 분석으로 생성되어 있어야 합니다.
        path = (
            log_dir
            / (
                f"{scenario}"
                "_tracking_summary.csv"
            )
        )

        # ======================================================
        # ⑲ 48번 요약 CSV가 없으면 오류 발생
        # ======================================================
        # 필수 입력 파일이 없으면 분석을 이어갈 수 없습니다.
        # 48번 Tracking Log 분석을 먼저 실행하도록 안내하며 중단합니다.
        if not path.exists():
            raise FileNotFoundError(
                "먼저 48번 분석을 "
                f"실행하세요: {path}"
            )

        # ======================================================
        # ⑳ Pandas로 Scenario별 Tracking 요약 CSV 읽기
        # ======================================================
        # 48번의 *_tracking_summary.csv 파일을 읽어 DataFrame으로 만듭니다.
        # 영상 전체의 추적 비율, Track ID 수 등이 들어 있다고 가정합니다.
        df = pd.read_csv(
            path
        )

        # ======================================================
        # ㉑ 요약 CSV가 정확히 한 행인지 확인
        # ======================================================
        # 48번의 영상 전체 Tracking Summary는 Scenario별로 한 행입니다.
        # 0행이거나 여러 행이면 잘못된 입력으로 보고 오류를 발생시킵니다.
        if len(df) != 1:
            raise RuntimeError(
                "Tracking Summary가 "
                f"한 행이 아닙니다: {path}"
            )

        # ======================================================
        # ㉒ 현재 Scenario의 요약 한 행을 목록에 추가
        # ======================================================
        # iloc[0]으로 첫 번째 행을 선택하고 to_dict()로 딕셔너리로 바꿉니다.
        # 그 값을 rows에 추가한 뒤 다음 Scenario를 처리합니다.
        rows.append(
            df.iloc[0].to_dict()
        )

    # ======================================================
    # ㉓ 모든 Scenario 결과를 하나의 비교표로 통합
    # ======================================================
    # rows에 모은 결과를 하나의 DataFrame으로 만듭니다.
    # 기본 Scenario 세 개를 모두 읽었다면 비교표는 세 행이 됩니다.
    result = pd.DataFrame(
        rows
    )

    # ======================================================
    # ㉔ 결과 CSV가 저장될 폴더 생성
    # ======================================================
    # experiments 폴더가 없다면 부모 폴더까지 자동 생성합니다.
    # exist_ok=True이므로 이미 있으면 그대로 사용합니다.
    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    # ======================================================
    # ㉕ Scenario 비교표를 UTF-8 CSV로 저장
    # ======================================================
    # Pandas 인덱스는 저장하지 않고(index=False),
    # 한글이 포함될 수 있으므로 utf-8-sig로 저장합니다.
    result.to_csv(
        output_path,
        index=False,
        encoding="utf-8-sig",
    )

    # ======================================================
    # ㉖ 비교 결과표를 터미널에 출력
    # ======================================================
    # to_string(index=False)로 요약된 Scenario 비교표를 출력합니다.
    # CSV를 열기 전에도 결과를 빠르게 확인할 수 있습니다.
    print(
        result.to_string(
            index=False
        )
    )

    print()

    # ======================================================
    # ㉗ 최종 비교 CSV 저장 위치 출력
    # ======================================================
    # 저장한 CSV 파일의 전체 경로를 안내합니다.
    # 학생들은 이 경로를 따라가 결과 파일을 확인합니다.
    print(
        f"Saved: {output_path}"
    )


# ======================================================
# ㉘ Python 직접 실행 시 main 함수 호출
# ======================================================
# 이 파일을 직접 실행했을 때만 main()을 호출합니다.
# 다른 Python 코드에서 import하면 자동 실행되지 않습니다.
if __name__ == "__main__":
    main()